// Copies the generated validators' numeric limits (`export const xMax = 200;`)
// into src/api/gen/validatorLimits.ts. A module lands whole in one chunk, so a
// page that needs only a limit (the app's entry: the search field, Make a
// quiz's title) imports this file instead of loading every zod schema with it
// (Q908). validators.ts keeps its own copies, so its schemas stay inlined.
import { readFileSync, writeFileSync } from 'node:fs';

const source = readFileSync(
  new URL('../src/api/gen/validators.ts', import.meta.url),
  'utf8'
);
const limit = /^export const \w+ = -?\d+(?:\.\d+)?(?:e[+-]?\d+)?;$/;
const limits = source.split('\n').filter((line) => limit.test(line));
if (limits.length === 0)
  throw new Error('no numeric limits found in validators.ts');

const header =
  "// Generated by scripts/gen-validator-limits.mjs from orval's validators.\n// Do not edit manually.\n";
writeFileSync(
  new URL('../src/api/gen/validatorLimits.ts', import.meta.url),
  `${header}${limits.join('\n')}\n`
);
process.stdout.write(`wrote ${limits.length} limits to validatorLimits.ts\n`);
