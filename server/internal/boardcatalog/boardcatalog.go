// Package boardcatalog lists every kind of thing a drawing board may hold: the canvas
// elements and blocks, which board takes each (a question's answer board or the
// workspace canvas), and the limits their checks use. `pnpm gen:openapi` writes it
// for the browser, whose loader, toolbar and preview read it (openwiki/frontend/
// plate-editor.md, Epo 2026-11-09).
package boardcatalog

import (
	"bytes"
	"encoding/json"
	"fmt"

	"github.com/samyung0/capy-notebook/server/internal/fieldlimits"
)

// TypeScriptPath is the generated browser file, relative to the repository root.
const TypeScriptPath = "src/api/board.generated.ts"

const generatedBy = "Generated by server/cmd/openapi from server/internal/boardcatalog. Do not edit manually."

// The boards. A kind lists the ones that may hold it.
const (
	Question  = "question"
	Workspace = "workspace"
)

var both = []string{Question, Workspace}

// Element is a kind on the canvas layer (the surface's elements).
type Element struct {
	Type   string   `json:"type"`
	Boards []string `json:"boards"`
}

// Block is a kind on the block tree, with the blocks it may sit under.
type Block struct {
	Flavour string   `json:"flavour"`
	Parents []string `json:"parents"`
	Boards  []string `json:"boards"`
}

// Catalog is the whole list.
type Catalog struct {
	Boards   []string         `json:"boards"`
	Elements []Element        `json:"elements"`
	Blocks   []Block          `json:"blocks"`
	Limits   map[string]int64 `json:"limits"`
}

// Get is the catalog.
func Get() Catalog {
	return Catalog{
		Boards: both,
		Elements: []Element{
			{Type: "brush", Boards: both},
			{Type: "highlighter", Boards: both},
			{Type: "shape", Boards: both},
			{Type: "connector", Boards: both},
			{Type: "text", Boards: both},
			{Type: "group", Boards: both},
			{Type: "plane", Boards: both},
			{Type: "chart", Boards: both},
			{Type: "formula", Boards: both},
			// AFFiNE's mind map: its topics and ideas are shapes it lays out.
			{Type: "mindmap", Boards: []string{Workspace}},
		},
		Blocks: []Block{
			{Flavour: "affine:page", Parents: []string{}, Boards: both},
			{Flavour: "affine:surface", Parents: []string{"affine:page"}, Boards: both},
			{Flavour: "affine:note", Parents: []string{"affine:page"}, Boards: both},
			{Flavour: "affine:paragraph", Parents: []string{"affine:note", "affine:paragraph", "affine:list"}, Boards: both},
			{Flavour: "affine:list", Parents: []string{"affine:note", "affine:paragraph", "affine:list"}, Boards: both},
			{Flavour: "affine:image", Parents: []string{"affine:surface", "affine:note"}, Boards: both},
			// A picture that plays by itself: an animated emoji, or a KLIPY GIF by link.
			{Flavour: "affine:embed-capy-picture", Parents: []string{"affine:surface"}, Boards: []string{Workspace}},
			// A link card (a YouTube video shows its poster) and a workspace quiz or set.
			{Flavour: "affine:embed-capy-link", Parents: []string{"affine:surface"}, Boards: []string{Workspace}},
			{Flavour: "affine:embed-capy-material", Parents: []string{"affine:surface"}, Boards: []string{Workspace}},
		},
		Limits: map[string]int64{
			// A plane's marks, and a label's characters (plane labels, chart labels).
			"MARKS_MAX":        500,
			"LABEL_LENGTH_MAX": 24,
			// A formula's LaTeX, as a card or a plane mark.
			"LATEX_MAX": 2000,
			// A bar chart's bars and its axis top; a pie's lines and labels.
			"BARS_MAX":   24,
			"AXIS_MAX":   1_000_000_000,
			"SPOKES_MAX": 60,
			"LABELS_MAX": 60,
			// A picture's label (an emoji, a GIF's title) and its link.
			"PICTURE_LABEL_MAX": 120,
			"PICTURE_REF_MAX":   2048,
			// A link card's address, and a material card's title (a material's own).
			"LINK_URL_MAX":    2048,
			"CARD_TITLE_MAX":  fieldlimits.MaterialTitle,
			"MATERIAL_ID_MAX": 64,
		},
	}
}

// TypeScript is the catalog for the browser, typed by its literal values.
func TypeScript() ([]byte, error) {
	var body bytes.Buffer
	enc := json.NewEncoder(&body)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(Get()); err != nil {
		return nil, err
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// %s\n", generatedBy)
	out.WriteString("export const BOARD_CATALOG = ")
	out.Write(bytes.TrimRight(body.Bytes(), "\n"))
	out.WriteString(" as const;\n")
	return out.Bytes(), nil
}
