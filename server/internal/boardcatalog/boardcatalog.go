// TypeScript is the catalog for the browser, typed by its literal values.
func TypeScript() ([]byte, error) {
	var body bytes.Buffer
	enc := json.NewEncoder(&body)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(Get()); err != nil {
		return nil, err
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// %s\n", generatedBy)
	out.WriteString("export const BOARD_CATALOG = ")
	out.Write(bytes.TrimRight(body.Bytes(), "\n"))
	out.WriteString(" as const;\n")
	return out.Bytes(), nil
}

// Rust is the catalog for the collaboration server (crate board): the same kinds,
// every limit as a constant and the emoji.
func Rust() []byte {
	c := Get()
	var out bytes.Buffer
	fmt.Fprintf(&out, "//! %s\n", generatedBy)
	out.WriteString("//! The board catalog (openwiki/frontend/plate-editor.md): what each drawing\n")
	out.WriteString("//! board holds, the limits its checks use and the picture emoji.\n\n")
	fmt.Fprintf(&out, "pub const BOARDS: &[&str] = %s;\n", rustStrs(c.Boards))
	out.WriteString(`
/// A kind on the canvas layer (the surface's elements).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Element {
    pub kind: &'static str,
    pub boards: &'static [&'static str],
}

/// A kind on the block tree, with the blocks it may sit under.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Block {
    pub flavour: &'static str,
    pub parents: &'static [&'static str],
    pub boards: &'static [&'static str],
}

pub const ELEMENTS: &[Element] = &[
`)
	for _, e := range c.Elements {
		fmt.Fprintf(&out, "    Element {\n        kind: %q,\n        boards: %s,\n    },\n", e.Type, rustStrs(e.Boards))
	}
	out.WriteString("];\n\npub const BLOCKS: &[Block] = &[\n")
	for _, b := range c.Blocks {
		fmt.Fprintf(&out, "    Block {\n        flavour: %q,\n        parents: %s,\n        boards: %s,\n    },\n",
			b.Flavour, rustStrs(b.Parents), rustStrs(b.Boards))
	}
	out.WriteString("];\n\n")
	names := make([]string, 0, len(c.Limits))
	for name := range c.Limits {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		fmt.Fprintf(&out, "pub const %s: usize = %d;\n", name, c.Limits[name])
	}
	out.WriteString("\npub const EMOJI: &[&str] = &[\n")
	for _, code := range c.Emoji {
		fmt.Fprintf(&out, "    %q,\n", code)
	}
	out.WriteString(`];

/// The element kind ` + "`kind`" + `, if the catalog lists it.
pub fn element(kind: &str) -> Option<&'static Element> {
    ELEMENTS.iter().find(|e| e.kind == kind)
}

/// The block flavour ` + "`flavour`" + `, if the catalog lists it.
pub fn block(flavour: &str) -> Option<&'static Block> {
    BLOCKS.iter().find(|b| b.flavour == flavour)
}
`)
	return out.Bytes()
}

func rustStrs(values []string) string {
	if len(values) == 0 {
		return "&[]"
	}
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = fmt.Sprintf("%q", v)
	}
	return "&[" + strings.Join(quoted, ", ") + "]"
}
